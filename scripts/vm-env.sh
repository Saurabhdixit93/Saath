#!/usr/bin/env bash
# Writes a fresh .env for a single-VM docker compose deploy, with newly generated secrets.
#
# Usage (from the repo root, after `docker compose build api`):
#   ./scripts/vm-env.sh <public-ip-or-host> <admin-email>[,<admin-email>...]
#
# The previous .env is kept as .env.bak.<timestamp>. POSTHOG_API_KEY is carried over from it.
# Rotating PNR_PEPPER / PHONE_* makes existing hashed rows unreadable, so only use on a fresh DB
# (or follow with `docker compose down -v`).
set -euo pipefail

HOST="${1:?usage: $0 <public-ip-or-host> <admin-email>}"
ADMIN_EMAILS="${2:?usage: $0 <public-ip-or-host> <admin-email>}"
WEB_PORT="${WEB_PORT:-29400}"
API_PORT="${API_PORT:-29401}"
ADMIN_PORT="${ADMIN_PORT:-29402}"

cd "$(dirname "$0")/.."

POSTHOG_API_KEY=""
if [[ -f .env ]]; then
  POSTHOG_API_KEY="$(grep -E '^POSTHOG_API_KEY=' .env | head -1 | cut -d= -f2- || true)"
  cp .env ".env.bak.$(date +%s)"
fi

# Generate keys with the api image's Python (it already ships `cryptography`).
SECRETS="$(docker compose run --rm --no-deps -T --entrypoint python api - <<'PY'
import base64, secrets
from cryptography.hazmat.primitives import serialization as s
from cryptography.hazmat.primitives.asymmetric import ec, ed25519

def ed_pair():
    k = ed25519.Ed25519PrivateKey.generate()
    priv = k.private_bytes(s.Encoding.PEM, s.PrivateFormat.PKCS8, s.NoEncryption())
    pub = k.public_key().public_bytes(s.Encoding.PEM, s.PublicFormat.SubjectPublicKeyInfo)
    return [x.decode().strip().replace("\n", "\\n") for x in (priv, pub)]

b64 = lambda n: base64.b64encode(secrets.token_bytes(n)).decode()
b64u = lambda b: base64.urlsafe_b64encode(b).rstrip(b"=").decode()

jwt_priv, jwt_pub = ed_pair()
card_priv, card_pub = ed_pair()
v = ec.generate_private_key(ec.SECP256R1())
vapid_priv = b64u(v.private_numbers().private_value.to_bytes(32, "big"))
vapid_pub = b64u(v.public_key().public_bytes(s.Encoding.X962, s.PublicFormat.UncompressedPoint))

print(f'JWT_PRIVATE_KEY="{jwt_priv}"')
print(f'JWT_PUBLIC_KEY="{jwt_pub}"')
print(f'SWAP_CARD_SIGNING_PRIVATE_KEY="{card_priv}"')
print(f'SWAP_CARD_SIGNING_PUBLIC_KEY="{card_pub}"')
print(f"PNR_PEPPER={secrets.token_urlsafe(32)}")
print(f"PHONE_AES_KEY={b64(32)}")
print(f"PHONE_BLIND_INDEX_KEY={b64(32)}")
print(f"INVITE_TOKEN_SECRET={secrets.token_urlsafe(32)}")
print(f"WHATSAPP_APP_SECRET={secrets.token_urlsafe(32)}")
print(f"VAPID_PUBLIC_KEY={vapid_pub}")
print(f"VAPID_PRIVATE_KEY={vapid_priv}")
print(f"NEXT_PUBLIC_VAPID_PUBLIC_KEY={vapid_pub}")
PY
)"

APP_URL="http://${HOST}:${WEB_PORT}"
API_URL="http://${HOST}:${API_PORT}"
ADMIN_URL="http://${HOST}:${ADMIN_PORT}"

cat > .env <<EOF
# Generated by scripts/vm-env.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)
# ENV=development keeps fake WhatsApp/SMS/rail/payment adapters allowed; production forbids them.
ENV=development
APP_URL=${APP_URL}
API_BASE_URL=${API_URL}
ADMIN_URL=${ADMIN_URL}
CORS_ORIGINS=${APP_URL},${ADMIN_URL}
LOG_LEVEL=INFO
OTEL_SERVICE_NAME=saath-api
POSTHOG_API_KEY=${POSTHOG_API_KEY}
POSTHOG_HOST=https://us.i.posthog.com

POSTGRES_USER=saath
POSTGRES_PASSWORD=saath
POSTGRES_DB=saath
DATABASE_URL=postgresql+asyncpg://saath:saath@postgres:5432/saath
REDIS_URL=redis://redis:6379/0
DOCKER_DATABASE_URL=postgresql+asyncpg://saath:saath@postgres:5432/saath
DOCKER_REDIS_URL=redis://redis:6379/0

JWT_ALGORITHM=EdDSA
JWT_ACCESS_TTL_SECONDS=900
JWT_ANON_TTL_SECONDS=7200
REFRESH_TOKEN_TTL_DAYS=30
ADMIN_SSO_ALLOWED_EMAILS=${ADMIN_EMAILS}
${SECRETS}

# Cloudflare's always-pass test keys; replace with real ones before going public.
TURNSTILE_MODE=cloudflare
TURNSTILE_SITE_KEY=1x00000000000000000000AA
TURNSTILE_SECRET_KEY=1x0000000000000000000000000000000AA
RAIL_PROVIDER_MODE=fake
PROVIDER_RAIL_TIMEOUT_MS=3000
FLIGHT_PROVIDER_MODE=fake
WHATSAPP_MODE=fake
SMS_MODE=fake
MSG91_SENDER_ID=SAATHI
PUSH_MODE=vapid
VAPID_SUBJECT=mailto:privacy@saath.app
AI_MODE=fake
ANTHROPIC_CONCIERGE_MODEL=claude-sonnet-5-5
ANTHROPIC_FAST_MODEL=claude-haiku-5-5
PAYMENT_PROVIDER=sandbox

# Baked into the web/admin browser bundles at build time (see docker-compose.yml build.args).
NEXT_PUBLIC_API_URL=${API_URL}
NEXT_PUBLIC_WS_URL=ws://${HOST}:${API_PORT}/v1/ws
NEXT_PUBLIC_APP_URL=${APP_URL}
NEXT_PUBLIC_TURNSTILE_MODE=cloudflare
NEXT_PUBLIC_TURNSTILE_SITE_KEY=1x00000000000000000000AA
NEXT_PUBLIC_ADMIN_SSO_ENABLED=false

WEB_PORT=${WEB_PORT}
API_PORT=${API_PORT}
ADMIN_PORT=${ADMIN_PORT}
EOF

chmod 600 .env
echo "Wrote .env for ${HOST} (backup of the old one kept as .env.bak.*)."
